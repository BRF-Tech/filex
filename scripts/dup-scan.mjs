/** A stable key for a finding: the set of files it spans. */
export function findingSignature(finding) {
  return [...new Set(finding.sites.map((s) => s.file))].sort().join(' <> ');
}

export function scan(opts = {}) {
  const t0 = Date.now();
  const cfg = { ...DEFAULTS, ...opts };
  const files = collectFiles(cfg.roots ?? SCAN_ROOTS, cfg.repoRoot ?? REPO_ROOT);
  const stream = buildStream(files);

  const renamedVals = renamedValues(stream);

  const verbatim = findClones({
    values: stream.v,
    shapeValues: renamedVals,
    kinds: stream.t,
    stream,
    k: cfg.minVerbatim,
    maxOcc: cfg.maxOccurrences,
    minShape: cfg.minShapeVerbatim,
  });

  const renamed = findClones({
    values: renamedVals,
    shapeValues: renamedVals,
    kinds: stream.t,
    stream,
    k: cfg.minRenamed,
    maxOcc: cfg.maxOccurrences,
    minShape: cfg.minShapeRenamed,
  });

  const findings = [];
  const seen = new Set();
  const emit = (kind, list) => {
    for (const c of list) {
      const sites = c.sites.map((s) => describeSite(stream, s.start, s.len));
      const f = { kind, tokens: c.tokens, sites };
      // A verbatim clone is also a renamed clone; report it once, as the
      // stronger claim.
      const key = `${findingSignature(f)}|${sites.map((s) => s.startLine).join(',')}`;
      if (seen.has(key)) continue;
      seen.add(key);
      f.lines = Math.max(...sites.map((s) => s.endLine - s.startLine + 1));
      findings.push(f);
    }
  };
  emit('verbatim', verbatim);
  emit('renamed', renamed);

  findings.sort((a, b) => b.tokens - a.tokens);

  const repoRoot = cfg.repoRoot ?? REPO_ROOT;
  const concepts = cfg.skipConcepts ? [] : scanConcepts(repoRoot);
  const composition = cfg.skipConcepts ? [] : scanComposition(repoRoot);

  return {
    generatedAt: new Date().toISOString(),
    config: {
      minVerbatim: cfg.minVerbatim,
      minRenamed: cfg.minRenamed,
      minShapeVerbatim: cfg.minShapeVerbatim,
      minShapeRenamed: cfg.minShapeRenamed,
      maxOccurrences: cfg.maxOccurrences,
      roots: cfg.roots ?? SCAN_ROOTS,
    },
    stats: {
      files: files.length,
      units: stream.units.length,
      tokens: stream.v.length,
      ms: Date.now() - t0,
    },
    findings,
    concepts,
    composition,
  };
}

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

function main(argv) {
  const opts = {};
  let json = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--json') json = true;
    else if (a === '--min-verbatim') opts.minVerbatim = Number(argv[++i]);
    else if (a === '--min-renamed') opts.minRenamed = Number(argv[++i]);
    else if (a === '--min-shape-verbatim') opts.minShapeVerbatim = Number(argv[++i]);
    else if (a === '--min-shape-renamed') opts.minShapeRenamed = Number(argv[++i]);
    else if (a === '--max-occ') opts.maxOccurrences = Number(argv[++i]);
    else if (a === '--only') (opts.roots ??= []).push(argv[++i]);
    else if (a === '--root') opts.repoRoot = path.resolve(argv[++i]);
  }
  const out = scan(opts);
  if (json) {
    process.stdout.write(JSON.stringify(out, null, 2));
    return;
  }
  const { stats, findings, config } = out;
  console.log(
    `dup-scan: ${stats.files} files, ${stats.tokens.toLocaleString('en-US')} tokens, ${stats.ms} ms`,
  );
  console.log(
    `thresholds: verbatim >= ${config.minVerbatim} tokens / ${config.minShapeVerbatim} shape, ` +
      `renamed >= ${config.minRenamed} tokens / ${config.minShapeRenamed} shape`,
  );
  console.log(`\n== duplicated fragments: ${findings.length} ==\n`);
  findings.forEach((f, i) => {
    console.log(`${String(i + 1).padStart(3)}. [${f.kind}] ${f.tokens} tokens`);
    for (const s of f.sites) console.log(`     ${s.file}:${s.startLine}-${s.endLine}`);
    console.log('');
  });

  const strays = out.concepts.filter((c) => c.strays.length);
  console.log(`== concepts implemented outside their home: ${strays.length} ==\n`);
  for (const c of strays) {
    console.log(`  ${c.id} — ${c.what}`);
    console.log(`     home: ${c.home.join(', ')}`);
    for (const s of c.strays) console.log(`     ${s.file}:${s.lines.join(',')}`);
    console.log(`     fix: ${c.fix}\n`);
  }

  const comp = out.composition.flatMap((r) => r.violations.map((v) => ({ rule: r.id, ...v })));
  console.log(`== surfaces that build their own chrome: ${comp.length} ==\n`);
  for (const v of comp) {
    console.log(`  ${v.file} renders ${v.renders.join(', ')}`);
    console.log(`     but does not use: ${v.missing.join(', ')}\n`);
  }

  if (findings.length || strays.length || comp.length) process.exitCode = 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}

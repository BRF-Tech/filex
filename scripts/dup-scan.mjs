/**
 * Reserved words are STRUCTURE, not names.
 *
 * They stay themselves in the renamed pass, which is what makes the shape
 * filter mean anything: with keywords blanked to `$ID` alongside every
 * variable, a 110-token block carries almost no distinct structural tokens and
 * the filter either passes everything or nothing. (Measured: with keywords
 * blanked, `minDistinctShape: 12` found 3 clones in the whole tree at every
 * token floor from 40 to 110 — the filter was answering a question about
 * punctuation.)
 */
const JS_RESERVED = new Set([
  'abstract', 'as', 'async', 'await', 'break', 'case', 'catch', 'class', 'const',
  'continue', 'declare', 'default', 'delete', 'do', 'else', 'enum', 'export',
  'extends', 'false', 'finally', 'for', 'from', 'function', 'get', 'if',
  'implements', 'import', 'in', 'infer', 'instanceof', 'interface', 'is',
  'keyof', 'let', 'namespace', 'new', 'null', 'of', 'private', 'protected',
  'public', 'readonly', 'return', 'satisfies', 'set', 'static', 'super',
  'switch', 'this', 'throw', 'true', 'try', 'type', 'typeof', 'undefined',
  'var', 'void', 'while', 'yield',
]);

const GO_RESERVED = new Set([
  'append', 'bool', 'break', 'byte', 'cap', 'case', 'chan', 'close', 'complex',
  'const', 'continue', 'copy', 'default', 'defer', 'delete', 'else', 'error',
  'fallthrough', 'false', 'float32', 'float64', 'for', 'func', 'go', 'goto',
  'if', 'import', 'int', 'int32', 'int64', 'interface', 'iota', 'len', 'make',
  'map', 'new', 'nil', 'package', 'panic', 'range', 'recover', 'return',
  'rune', 'select', 'string', 'struct', 'switch', 'true', 'type', 'uint',
  'uint32', 'uint64', 'var',
]);

/** Reserved words that END an expression, so a following `/` is division. */
const JS_VALUE_KEYWORDS = new Set(['this', 'super', 'true', 'false', 'null', 'undefined']);

const JS_PUNCT = [
  '>>>=', '...', '===', '!==', '**=', '<<=', '>>=', '>>>', '&&=', '||=', '??=',
  '=>', '==', '!=', '<=', '>=', '&&', '||', '??', '?.', '++', '--', '+=', '-=',
  '*=', '/=', '%=', '&=', '|=', '^=', '**', '<<', '>>',
  '{', '}', '(', ')', '[', ']', ';', ',', '<', '>', '+', '-', '*', '/', '%',
  '&', '|', '^', '!', '~', '?', ':', '=', '.', '@', '#',
];

const GO_PUNCT = [
  '<<=', '>>=', '&^=', '...', '&^', ':=', '<-', '++', '--', '==', '!=', '<=',
  '>=', '&&', '||', '+=', '-=', '*=', '/=', '%=', '&=', '|=', '^=', '<<', '>>',
  '{', '}', '(', ')', '[', ']', ';', ',', '<', '>', '+', '-', '*', '/', '%',
  '&', '|', '^', '!', '~', '?', ':', '=', '.',
];

const IDENT_START = /[A-Za-z_$]/;
const IDENT_PART = /[A-Za-z0-9_$]/;

/**
 * Turn source into `{ v, t, line }` tokens. Comments and whitespace vanish.
 *
 * `t` is one of: id | num | str | punct. The caller decides what to do with
 * the value; both passes share this stream so a file is lexed once.
 */
export function tokenize(src, lang, opts = {}) {
  const commentRanges = opts.commentRanges;
  const punct = lang === 'go' ? GO_PUNCT : JS_PUNCT;
  const reserved = lang === 'go' ? GO_RESERVED : JS_RESERVED;
  const out = [];
  let i = 0;
  let line = 1;
  const n = src.length;
  /**
   * Explicit mode stack for template literals. `code` counts open braces so we
   * know which `}` ends an interpolation; `tpl` means we are inside the string
   * part. Nesting works because a nested backtick just pushes another `tpl`.
   */
  const modes = [{ kind: 'code', depth: 0 }];
  const mode = () => modes[modes.length - 1];

  const push = (v, t) => out.push({ v, t, line });
  const prev = () => (out.length ? out[out.length - 1] : null);

  const countNewlines = (from, to) => {
    for (let k = from; k < to; k++) if (src.charCodeAt(k) === 10) line++;
  };

  while (i < n) {
    const c = src[i];

    // Inside the literal text of a template: consume until the literal ends
    // or an interpolation opens. One `$STR` stands for the whole chunk.
    if (mode().kind === 'tpl') {
      let j = i;
      let emitted = false;
      while (j < n) {
        if (src[j] === '\\') { j += 2; continue; }
        if (src[j] === '`') { modes.pop(); j++; break; }
        if (src[j] === '$' && src[j + 1] === '{') break;
        if (src[j] === '\n') line++;
        j++;
        emitted = true;
      }
      if (emitted) push('$STR', 'str');
      if (j < n && src[j] === '$' && src[j + 1] === '{') {
        push('${', 'punct');
        modes.push({ kind: 'code', depth: 0 });
        j += 2;
      }
      i = j > i ? j : i + 1;
      continue;
    }

    if (c === '\n') { line++; i++; continue; }
    if (c === ' ' || c === '\t' || c === '\r') { i++; continue; }

    // comments
    if (c === '/' && src[i + 1] === '/') {
      const nl = src.indexOf('\n', i);
      const stop = nl < 0 ? n : nl;
      if (commentRanges) commentRanges.push([i, stop]);
      i = stop;
      continue;
    }
    if (c === '/' && src[i + 1] === '*') {
      const end = src.indexOf('*/', i + 2);
      const stop = end < 0 ? n : end + 2;
      if (commentRanges) commentRanges.push([i, stop]);
      countNewlines(i, stop);
      i = stop;
      continue;
    }

    // strings
    if (c === '"' || c === "'" || (lang === 'go' && c === '`')) {
      const quote = c;
      let j = i + 1;
      while (j < n) {
        if (src[j] === '\\' && quote !== '`') { j += 2; continue; }
        if (src[j] === quote) { j++; break; }
        if (src[j] === '\n' && quote !== '`') { j++; break; }
        j++;
      }
      push('$STR', 'str');
      countNewlines(i, j);
      i = j;
      continue;
    }

    // JS template literal — the literal chunks become $STR, the `${}`
    // expressions are tokenized normally so logic inside them still counts.
    if (lang !== 'go' && c === '`') {
      modes.push({ kind: 'tpl' });
      i++;
      continue;
    }

    // Braces, tracked so the `}` that closes an interpolation pops back into
    // the literal instead of being read as the end of a block.
    if (lang !== 'go' && (c === '{' || c === '}')) {
      const m = mode();
      if (c === '{') {
        m.depth++;
        push('{', 'punct');
      } else if (m.depth === 0 && modes.length > 1) {
        modes.pop(); // back into the surrounding `tpl`
        push('}$', 'punct');
      } else {
        m.depth--;
        push('}', 'punct');
      }
      i++;
      continue;
    }

    // regex literal (JS only) — a `/` here is a regex when the previous
    // significant token cannot end an expression.
    if (lang !== 'go' && c === '/') {
      const p = prev();
      let regexOk = true;
      if (p) {
        if (p.t === 'num' || p.t === 'str' || p.t === 'id') regexOk = false;
        else if (p.t === 'kw') regexOk = !JS_VALUE_KEYWORDS.has(p.v);
        else if (p.v === ')' || p.v === ']' || p.v === '++' || p.v === '--') regexOk = false;
      }
      if (regexOk) {
        let j = i + 1;
        let klass = false;
        let ok = false;
        while (j < n) {
          const d = src[j];
          if (d === '\\') { j += 2; continue; }
          if (d === '\n') break;
          if (d === '[') klass = true;
          else if (d === ']') klass = false;
          else if (d === '/' && !klass) { j++; ok = true; break; }
          j++;
        }
        if (ok) {
          while (j < n && /[a-z]/.test(src[j])) j++;
          push('$RE', 'str');
          i = j;
          continue;
        }
      }
    }

    // numbers
    if (/[0-9]/.test(c) || (c === '.' && /[0-9]/.test(src[i + 1] || ''))) {
      let j = i;
      while (j < n && /[0-9a-fA-FxXoObBeEnN_.+-]/.test(src[j])) {
        // stop a `+`/`-` that is not an exponent sign
        if ((src[j] === '+' || src[j] === '-') && !/[eE]/.test(src[j - 1])) break;
        if (src[j] === '.' && src[j + 1] === '.') break;
        j++;
      }
      push('$NUM', 'num');
      i = j;
      continue;
    }

    // identifiers and reserved words
    if (IDENT_START.test(c)) {
      let j = i + 1;
      while (j < n && IDENT_PART.test(src[j])) j++;
      const word = src.slice(i, j);
      push(word, reserved.has(word) ? 'kw' : 'id');
      i = j;
      continue;
    }

    // punctuation
    let matched = null;
    for (const p of punct) {
      if (src.startsWith(p, i)) { matched = p; break; }
    }
    if (matched) {
      push(matched, 'punct');
      i += matched.length;
      continue;
    }

    i++; // unknown byte
  }

  return out;
}

/** `<script>` blocks of a Vue SFC, with the line they start on. */
export function extractVueScripts(src) {
  const out = [];
  const re = /<script\b[^>]*>/gi;
  let m;
  while ((m = re.exec(src))) {
    const start = m.index + m[0].length;
    const end = src.indexOf('</script>', start);
    if (end < 0) break;
    let lineOffset = 0;
    for (let k = 0; k < start; k++) if (src.charCodeAt(k) === 10) lineOffset++;
    out.push({ code: src.slice(start, end), lineOffset });
    re.lastIndex = end + 9;
  }
  return out;
}


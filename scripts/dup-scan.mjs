/**
 * Paths that are not "the same logic written twice", with the reason.
 *
 * ⚠ This is a SCOPE list, not an escape hatch — it says "this file is not
 * hand-written logic". A real duplicate you do not want to fix goes in the
 * gate's LEGITIMATE_TWINS / KNOWN_DUPLICATION lists, where it is visible.
 */
export const SCOPE_EXCLUSIONS = [
  {
    match: (rel) => /(^|\/)locales\//.test(rel),
    why: 'en.ts and tr.ts are two catalogues of the same keys by design; that is the feature, not a clone',
  },
  {
    match: (rel) => /\.d\.ts$/.test(rel),
    why: 'generated type declarations',
  },
  {
    match: (rel) => /_test\.go$|\.test\.ts$|\.spec\.ts$/.test(rel),
    why: 'table-driven tests repeat on purpose',
  },
  {
    match: (rel) => /(^|\/)(testdata|node_modules|dist|embed)\//.test(rel),
    why: 'fixtures, build output, vendored trees',
  },
];

const CODE_EXT = new Set(['.ts', '.tsx', '.cts', '.mts', '.vue', '.go']);

/** First lines that mark a file as produced by a tool rather than a person. */
const GENERATED_RE = /Code generated by|@generated|DO NOT EDIT/i;

// ---------------------------------------------------------------------------
// Thresholds — see the header of the gate test for how these were chosen.
// ---------------------------------------------------------------------------

export const DEFAULTS = {
  /** Contiguous tokens, identifiers intact, before a copy-paste is a finding. */
  minVerbatim: 100,
  /** Contiguous tokens, identifiers blanked, before a re-typed block is a finding. */
  minRenamed: 140,
  /**
   * How many DISTINCT structural tokens a clone must carry — keywords and
   * operators; the ubiquitous `( ) , ; . { } [ ] :` and every name do not
   * count. It is the difference between duplicated LOGIC and a repeated data
   * table, and the two passes need very different floors:
   *
   * verbatim: low. Identical tokens INCLUDING the names is already strong
   *   evidence; the filter is only here to drop declarative tables — a theme
   *   map, a route list, a shortcut catalogue — where `$STR : $STR ,` repeats
   *   and the structural score is 0-2. Measured: at 14 this pass threw away a
   *   byte-for-byte identical 194-token block shared by ftpsrv/fileinfo.go and
   *   sftpsrv/fileinfo.go (score 10), which is exactly the kind of hit the
   *   gate exists for.
   *
   * renamed: high. Every name is `$ID` here, so the shape is ALL the evidence
   *   there is. Below ~12 the pass reports 110 tokens of `$ID.$ID($ID, $ID);`
   *   as a clone and the gate is noise inside a week.
   */
  minShapeVerbatim: 6,
  minShapeRenamed: 14,
  /**
   * Ignore a k-gram that occurs more often than this. A shape that appears 60
   * times is a language idiom, not a copied block, and pairing them up is
   * quadratic.
   */
  maxOccurrences: 24,
};


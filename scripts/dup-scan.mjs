#!/usr/bin/env node
/**
 * dup-scan — find the same logic written twice.
 *
 * WHY THIS EXISTS
 * ---------------
 * "Tekrar eden şeyler tek yerden eklenmeli, tek yerden yönetilmeli." Every
 * time that rule was broken in this repo it was caught by a person looking at
 * a screen, never by a check: a 464-line second listing pane, the same
 * `mime_type === 'inode/storage'` line in three view components, a brand mark
 * hand-built as an inline SVG in two more files after the component was
 * recoloured, two date formatters that disagreed. The second copy always gets
 * written because the first is inconvenient to reach, nothing notices, and the
 * two drift.
 *
 * WHAT IT LOOKS FOR
 * -----------------
 * Two passes over the same normalised token stream, because the real cases
 * come in two shapes and one threshold cannot serve both:
 *
 *   verbatim  identifiers kept as written. This is copy-paste: the block was
 *             moved with the mouse and the names came along. Cheap to be sure
 *             about, so the token floor can be low.
 *
 *   renamed   identifiers, strings and numbers collapsed to placeholders. This
 *             is the block that was re-typed, or copied and then adapted, so
 *             `parts`/`segs` and `part`/`s` no longer match. A line-hash or a
 *             value-token detector misses exactly this, and it is most of the
 *             list above — so it gets a higher token floor plus a much
 *             stricter shape filter (see DEFAULTS) to keep boilerplate out.
 *
 * Both passes report *maximal* clone groups: three copies of one fragment come
 * back as one finding with three sites, not three findings.
 *
 * WHAT IT DOES NOT LOOK FOR
 * -------------------------
 * - Vue `<template>` and `<style>` blocks. Logic only; repeated markup and
 *   repeated CSS are a different argument with a different answer.
 * - Behaviour. Two date formatters that disagree while sharing no tokens are
 *   invisible here — that one needs a test, not a scanner.
 * - Tests. `*_test.go` / `*.test.ts` are excluded: table-driven tests are
 *   repetitive on purpose and would drown the signal on day one.
 *
 * USE
 * ---
 *   node scripts/dup-scan.mjs                 human-readable ranked report
 *   node scripts/dup-scan.mjs --json          machine output (the gate uses this)
 *   node scripts/dup-scan.mjs --min-verbatim 60 --min-renamed 120
 *   node scripts/dup-scan.mjs --only packages/core/src
 *   node scripts/dup-scan.mjs --root <dir> --only src     (used by the gate's
 *                                                          own fixture tests)
 *
 * The gate that consumes it: web/tests/quality/duplication.test.ts
 */


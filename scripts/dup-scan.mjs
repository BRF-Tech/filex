function walk(dir, acc, exts = CODE_EXT) {
  const want = exts instanceof Set ? exts : new Set(exts);
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return acc;
  }
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === 'node_modules' || e.name === 'dist' || e.name === '.git') continue;
      walk(full, acc, want);
    } else if (e.isFile() && want.has(path.extname(e.name))) {
      acc.push(full);
    }
  }
  return acc;
}

/**
 * One read per file per process. The three mechanisms walk overlapping trees
 * (the brand mark lives in Go, HTML and Vue), and re-reading `backend/internal`
 * four times was most of the runtime.
 */
const readCache = new Map();
function readFile(abs) {
  let hit = readCache.get(abs);
  if (hit === undefined) {
    try { hit = fs.readFileSync(abs, 'utf8'); } catch { hit = null; }
    readCache.set(abs, hit);
  }
  return hit;
}

export function collectFiles(roots = SCAN_ROOTS, repoRoot = REPO_ROOT) {
  const files = [];
  for (const root of roots) {
    walk(path.join(repoRoot, root), files);
  }
  const kept = [];
  for (const abs of files) {
    const rel = path.relative(repoRoot, abs).split(path.sep).join('/');
    if (SCOPE_EXCLUSIONS.some((x) => x.match(rel))) continue;
    const src = readFile(abs);
    if (src === null || GENERATED_RE.test(src.slice(0, 400))) continue;
    kept.push({ rel, src });
  }
  kept.sort((a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0));
  return kept;
}


/**
 * One flat token stream for the whole corpus, plus the file/line each token
 * came from. A sentinel between files means no window can straddle two files.
 */
export function buildStream(files) {
  /** @type {{rel:string}[]} */
  const units = [];
  const v = [];      // token value
  const t = [];      // token kind
  const unit = [];   // index into units
  const ln = [];     // line in the source file

  for (const f of files) {
    const ext = path.extname(f.rel);
    if (ext === '.vue') {
      const blocks = extractVueScripts(f.src);
      for (const b of blocks) {
        const idx = units.length;
        units.push({ rel: f.rel });
        for (const tok of tokenize(b.code, 'js')) {
          v.push(tok.v); t.push(tok.t); unit.push(idx); ln.push(b.lineOffset + tok.line);
        }
      }
    } else {
      const idx = units.length;
      units.push({ rel: f.rel });
      const lang = ext === '.go' ? 'go' : 'js';
      for (const tok of tokenize(f.src, lang)) {
        v.push(tok.v); t.push(tok.t); unit.push(idx); ln.push(tok.line);
      }
    }
  }
  return { units, v, t, unit, ln };
}

/** Values for the `renamed` pass: names, strings and numbers become shapes. */
function renamedValues(stream) {
  const out = new Array(stream.v.length);
  for (let i = 0; i < out.length; i++) {
    const kind = stream.t[i];
    // Reserved words (`kind === 'kw'`) survive: they are the shape of the code.
    out[i] = kind === 'id' ? '$ID' : kind === 'num' ? '$NUM' : kind === 'str' ? '$STR' : stream.v[i];
  }
  return out;
}

// ---------------------------------------------------------------------------
// Clone detection
// ---------------------------------------------------------------------------

const NOISE_PUNCT = new Set(['(', ')', ',', ';', '.', '{', '}', '[', ']', ':']);

/** Distinct keyword/operator tokens in a slice — how much *shape* it carries. */
function distinctShape(values, kinds, from, len) {
  const seen = new Set();
  for (let i = from; i < from + len; i++) {
    const k = kinds[i];
    if (k === 'num' || k === 'str') continue;
    const val = values[i];
    if (k === 'punct' && NOISE_PUNCT.has(val)) continue;
    if (val === '$ID') continue;
    seen.add(val);
  }
  return seen.size;
}

function intern(values) {
  const map = new Map();
  const ids = new Int32Array(values.length);
  for (let i = 0; i < values.length; i++) {
    let id = map.get(values[i]);
    if (id === undefined) { id = map.size + 1; map.set(values[i], id); }
    ids[i] = id;
  }
  return ids;
}

/**
 * Maximal duplicated token runs of at least `k` tokens.
 *
 * Greedy left to right with a covered-bitmap, so a run is reported once as a
 * group of sites rather than once per shifted window, and the work stays
 * roughly linear in the corpus.
 */
function findClones({ values, shapeValues, kinds, stream, k, maxOcc, minShape }) {
  const n = values.length;
  if (n < k) return [];
  const ids = intern(values);
  const MOD = 0x100000000;
  const BASE = 1000003;

  let power = 1;
  for (let i = 0; i < k - 1; i++) power = Math.imul(power, BASE) >>> 0;

  const hashes = new Int32Array(n - k + 1);
  const spanOk = new Uint8Array(n - k + 1);
  let h = 0;
  for (let i = 0; i < k; i++) h = (Math.imul(h, BASE) + ids[i]) >>> 0;
  hashes[0] = h | 0;
  spanOk[0] = stream.unit[0] === stream.unit[k - 1] ? 1 : 0;
  for (let i = 1; i <= n - k; i++) {
    h = (h - Math.imul(ids[i - 1], power)) >>> 0;
    h = (Math.imul(h, BASE) + ids[i + k - 1]) >>> 0;
    hashes[i] = h | 0;
    spanOk[i] = stream.unit[i] === stream.unit[i + k - 1] ? 1 : 0;
  }

  /** @type {Map<number, number[]>} */
  const index = new Map();
  for (let i = 0; i <= n - k; i++) {
    if (!spanOk[i]) continue;
    const key = hashes[i];
    const bucket = index.get(key);
    if (bucket === undefined) index.set(key, [i]);
    else if (bucket.length <= maxOcc) bucket.push(i);
    else bucket.push(i); // keep counting so we can drop the whole bucket
  }

  const covered = new Uint8Array(n);
  const results = [];

  const sameRun = (a, b, len) => {
    const ua = stream.unit[a];
    const ub = stream.unit[b];
    for (let d = 0; d < len; d++) {
      if (stream.unit[a + d] !== ua || stream.unit[b + d] !== ub) return false;
      if (ids[a + d] !== ids[b + d]) return false;
    }
    return true;
  };

  for (let i = 0; i <= n - k; i++) {
    if (covered[i] || !spanOk[i]) continue;
    const bucket = index.get(hashes[i]);
    if (!bucket || bucket.length < 2 || bucket.length > maxOcc) continue;

    /** @type {{start:number,len:number}[]} */
    const partners = [];
    for (const j of bucket) {
      if (j <= i) continue;
      if (covered[j]) continue;
      if (j < i + k) continue; // overlapping windows in the same file
      if (!sameRun(i, j, k)) continue; // hash collision
      // extend right while the tokens agree and neither side leaves its file
      let len = k;
      const ua = stream.unit[i];
      const ub = stream.unit[j];
      while (
        i + len < n && j + len < n &&
        stream.unit[i + len] === ua && stream.unit[j + len] === ub &&
        ids[i + len] === ids[j + len] &&
        i + len < j
      ) len++;
      partners.push({ start: j, len });
    }
    if (partners.length === 0) continue;

    const len = Math.min(...partners.map((p) => p.len));
    // The shape score is ALWAYS read off the renamed projection, in both
    // passes. On the verbatim stream every distinct identifier would count,
    // so a theme map or a route table — many distinct keys, almost no
    // control flow — would score as the most structured code in the repo.
    if (minShape && distinctShape(shapeValues, kinds, i, len) < minShape) continue;

    const sites = [{ start: i, len }, ...partners.map((p) => ({ start: p.start, len }))];
    for (const s of sites) {
      for (let d = 0; d < s.len; d++) covered[s.start + d] = 1;
    }
    results.push({ tokens: len, sites });
  }

  return results;
}

function describeSite(stream, start, len) {
  const u = stream.unit[start];
  return {
    file: stream.units[u].rel,
    startLine: stream.ln[start],
    endLine: stream.ln[start + len - 1],
  };
}

// ---------------------------------------------------------------------------
// Second mechanism: one home per concept
// ---------------------------------------------------------------------------
//
// A token detector can only see a duplicate that is still SHAPED like the
// original. The worst cases in this repo are not: SecondaryPane re-implements
// the breadcrumb in 28 lines where Breadcrumb.vue takes 60, and the longest
// matching token run between the two files — with every identifier blanked —
// is 29 tokens. That is below any floor that would not also report every
// `if (!ok) return null` in the tree. (Measured both with this scanner and
// with jscpd 5.2's AST-similarity mode, which finds nothing between those two
// files at any setting from 0.85 down to 0.55.)
//
// So: a second, blunter mechanism. Some concepts have exactly one home here.
// Name the concept, name its home, name a `tell` that only that concept
// produces, and any OTHER file showing the tell is a second implementation. It
// catches the one-liner and the re-typed helper alike, because it does not
// care what the code looks like — only where it lives.

/** Strip comments, so a mention of a concept is not read as an instance of it. */
export function stripComments(src, ext) {
  let out = src;
  if (ext === '.html' || ext === '.svg' || ext === '.vue') {
    out = out.replace(/<!--[\s\S]*?-->/g, (m) => ' '.repeat(m.length));
  }
  if (ext === '.ts' || ext === '.tsx' || ext === '.cts' || ext === '.mts' || ext === '.go') {
    const ranges = [];
    tokenize(out, ext === '.go' ? 'go' : 'js', { commentRanges: ranges });
    out = blankRanges(out, ranges);
  }
  if (ext === '.vue') {
    // Only inside <script>: a `//` in the template is usually a URL.
    for (const b of extractVueScripts(out)) {
      const at = out.indexOf(b.code);
      if (at < 0) continue;
      const ranges = [];
      tokenize(b.code, 'js', { commentRanges: ranges });
      out = blankRanges(out, ranges.map(([a, z]) => [at + a, at + z]));
    }
  }
  return out;
}

function blankRanges(src, ranges) {
  if (!ranges.length) return src;
  const chars = [...src];
  for (const [a, z] of ranges) {
    for (let i = a; i < z && i < chars.length; i++) {
      if (chars[i] !== '\n') chars[i] = ' ';
    }
  }
  return chars.join('');
}

/**
 * Concepts with exactly one home.
 *
 * `tell` must be something ONLY that concept writes, and it must match inside
 * the home — the gate asserts that, so a concept that moves house fails loudly
 * instead of quietly passing everything.
 */
export const CONCEPTS = [
  {
    id: 'byte-size',
    what: 'turning a byte count into "1.4 GB"',
    /**
     * ONE home now. `web/src/lib/format.ts` used to be listed here too, and
     * that was the hole: two homes meant two bases (1000 there, 1024 in the
     * explorer) and nothing to say they disagreed. `formatBytes` delegates to
     * `formatByteSize` since 2026-09-13, so a hand-rolled formatter appearing
     * in format.ts again is a stray like any other.
     */
    home: ['packages/core/src/composables/useLocale.ts'],
    /**
     * Four alternatives, because a copy can be written four ways: a binary
     * ladder (1024), a decimal one (1000), a hardcoded unit table, or the
     * catalogue keys. The one implementation is generic over its base, so it
     * carries no ladder literal at all — `'unit.bytes'` is what identifies it,
     * and it is also what a translated copy would have to write.
     */
    tell: /\[\s*'B',\s*'KB'|\[\s*'K',\s*'M',\s*'G'|1024\s*\*\*|\/=\s*1024|>=\s*1024|1000\s*\*\*|\/=\s*1000|>=\s*1000|'unit\.bytes'/,
    roots: ['packages/core/src', 'web/src', 'desktop/src'],
    ext: ['.ts', '.vue'],
    fix: 'call formatByteSize() (or formatSize() from useLocale / formatBytes() from web/src/lib/format, which both do)',
  },
  {
    id: 'datetime-format',
    what: 'rendering an instant for a human',
    home: [
      'packages/core/src/composables/useLocale.ts',
      'packages/core/src/lib/timezone.ts',
      'web/src/lib/format.ts',
      'web/src/lib/timezone.ts',
    ],
    tell: /toLocaleDateString|toLocaleTimeString|toLocaleString\(|new Intl\.DateTimeFormat/,
    roots: ['packages/core/src', 'web/src', 'desktop/src'],
    ext: ['.ts', '.vue'],
    fix: "use formatDate()/formatDateFull() — they carry the viewer's locale AND chosen time zone",
  },
  {
    id: 'storage-row',
    what: 'recognising the synthetic "a storage" row in a listing',
    home: ['packages/core/src/lib/'],
    tell: /mime_type\s*===\s*'inode\/storage'/,
    roots: ['packages/core/src', 'web/src'],
    ext: ['.ts', '.vue'],
    fix: 'use the predicate from lib/fileIcons (or move it to lib/listing beside the other row helpers)',
  },
  {
    id: 'brand-mark',
    what: 'the filex logo',
    home: ['web/src/components/LogoMark.vue'],
    tell: /M7 11a2 2 0 0 1 2-2h5l2 2h7/,
    roots: ['packages/core/src', 'web/src', 'backend/internal', 'desktop/ui', 'site'],
    ext: ['.ts', '.vue', '.go', '.html', '.svg'],
    fix: 'generate the copy from LogoMark (the repo already syncs assets in scripts/sync-site-assets.mjs); do not re-type the path data',
  },
];

export function scanConcepts(repoRoot = REPO_ROOT) {
  const out = [];
  for (const concept of CONCEPTS) {
    const files = [];
    for (const root of concept.roots) walk(path.join(repoRoot, root), files, concept.ext);
    const homeHits = [];
    const strays = [];
    for (const abs of files) {
      const rel = path.relative(repoRoot, abs).split(path.sep).join('/');
      if (/(^|\/)(node_modules|dist|release|embed|build)\//.test(rel)) continue;
      if (SCOPE_EXCLUSIONS.some((x) => x.match(rel))) continue;
      const src = readFile(abs);
      if (src === null || !concept.tell.test(src)) continue;
      const clean = stripComments(src, path.extname(rel));
      const lines = [];
      clean.split('\n').forEach((l, i) => { if (concept.tell.test(l)) lines.push(i + 1); });
      if (!lines.length) continue;
      const atHome = concept.home.some((h) => (h.endsWith('/') ? rel.startsWith(h) : rel === h));
      (atHome ? homeHits : strays).push({ file: rel, lines });
    }
    strays.sort((a, b) => (a.file < b.file ? -1 : 1));
    out.push({ id: concept.id, what: concept.what, fix: concept.fix, home: concept.home, homeHits, strays });
  }
  return out;
}

// ---------------------------------------------------------------------------
// Third mechanism: a surface that reaches for SOME of the shared pieces
// ---------------------------------------------------------------------------
//
// What made SecondaryPane a second listing pane is not any line it contains.
// It is that it renders the three view components — so it IS a listing surface
// — while sourcing only two of the five shared pieces a listing surface is
// made of, and hand-rolling the rest. That is checkable from the import list,
// and it is exactly the defect: not "code that looks the same" but "a surface
// that decided to build its own".

export const COMPOSITION_RULES = [
  {
    id: 'listing-surface',
    what: 'a component that renders the shared view components is a listing surface',
    roots: ['packages/core/src', 'web/src'],
    /** Rendering this many of these makes a file a listing surface. */
    marker: ['ListView.vue', 'GridView.vue', 'GalleryView.vue'],
    markerMin: 2,
    /** …and a listing surface takes ALL of its chrome from these. */
    requires: [
      { import: 'Breadcrumb.vue', concept: 'the breadcrumb' },
      { import: 'FilterBar.vue', concept: 'the filter row' },
      { import: 'ViewSwitcher.vue', concept: 'the list/grid/gallery switch' },
      { import: 'lib/sortOrder', concept: 'the sort order' },
      { import: 'lib/listing', concept: 'the listing filter and the virtual rows' },
    ],
  },
];

export function scanComposition(repoRoot = REPO_ROOT) {
  const out = [];
  for (const rule of COMPOSITION_RULES) {
    const files = [];
    for (const root of rule.roots) walk(path.join(repoRoot, root), files, ['.vue']);
    const violations = [];
    const surfaces = [];
    for (const abs of files) {
      const rel = path.relative(repoRoot, abs).split(path.sep).join('/');
      const src = readFile(abs);
      if (src === null) continue;
      const clean = stripComments(src, '.vue');
      const imports = [...clean.matchAll(/import[^;']*?from\s*'([^']+)'/g)].map((m) => m[1]);
      const renders = rule.marker.filter((m) => imports.some((i) => i.endsWith(m)));
      if (renders.length < rule.markerMin) continue;
      const missing = rule.requires.filter(
        (r) => !imports.some((i) => i.endsWith(r.import) || i.endsWith(r.import.replace(/\.vue$/, ''))),
      );
      surfaces.push({ file: rel, renders, missing: missing.map((m) => m.import) });
      if (missing.length) {
        violations.push({
          file: rel,
          renders,
          missing: missing.map((m) => `${m.import} (${m.concept})`),
        });
      }
    }
    out.push({ id: rule.id, what: rule.what, surfaces, violations });
  }
  return out;
}


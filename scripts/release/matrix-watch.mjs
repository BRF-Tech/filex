// The full matrix BEHIND a server patch (task #252): reads GitHub's ci.yml
// on the release's export commit part by part, and when every part is green
// switches the update manifest's auto_ok on for the release; red, it says so
// and leaves it off.
//
//   node scripts/release/matrix-watch.mjs X.Y.Z [--env FILE] [--once] [--dry-run]
//
//   --env FILE   the release train's settings (default: $FILEX_TRAIN_ENV, else
//                ~/.config/filex-train.env): SHIP_MANIFEST_CMD publishes the
//                manifest, SHIP_HOST + SHIP_PURGE_CMD purge it from the CDN,
//                FILEX_NOTIFY_* / FILEX_WAKE_* say how it ended
//   --once       read once and say where it stands; never waits
//   --dry-run    read and decide, publish nothing
//
// Exit: 0 the matrix is green and auto_ok is on (or already was); 1 the
// matrix is red (auto_ok stays off) or the switch failed; 2 it could not
// start; 3 the matrix has not finished (--once, or the wait ran out).
//
// ⚠ Why: a server patch goes out once its own gates passed and GitHub built
// it (scripts/release/stages.mjs, the server lane), ~30 minutes after its code
// was done instead of two hours - and its update manifest entry says
// auto_ok false, so no install takes it by itself (docs/UPDATES.md) until the
// whole suite has run on it. This is the step that turns it on, without a
// person waiting for a 45-minute matrix. A red part is a finding for a
// person: nothing here re-runs it or switches anything on.
//
// The manifest is regenerated by SHIP_MANIFEST_CMD with FILEX_MANIFEST_AUTO
// naming the release (scripts/gen-update-manifest.py takes it from the
// environment, so a publishing wrapper that passes its own options alone
// carries it too), then read back.

import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { announce } from '../lib/notify.mjs';
import { loadSettings } from '../lib/settings.mjs';
import { shipSettings, sshWords } from '../train/ship.mjs';
import { usageOf } from '../train/cli.mjs';
import { partsLine, partsVerdict, runVerdict, transientGithubError } from './checks.mjs';
import { findBash, gitOut, loadState, saveState, shq, stateFile, takeLock } from './engine.mjs';
import { matrixState } from './stages.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..');

/** Where the manifest is served, to read it back. */
export const MANIFEST_URL = 'https://filex.sh/updates/stable.json';

/**
 * What a reading of the push run says to do: `auto` (every part green:
 * switch auto_ok on), `red` (a part failed or never ran: leave it off and
 * say so), `wait`. `runState` is runVerdict's, `parts` partsVerdict's (or
 * null before the run has jobs).
 */
export function watchVerdict(runState, parts) {
  if (runState === 'none') return { action: 'wait', why: 'no ci.yml run of the push yet' };
  const state = matrixState(runState, parts);
  if (state === 'success') return { action: 'auto', why: parts ? partsLine(parts) : 'the run passed' };
  if (state === 'failure') {
    const red = parts?.failed?.length ? parts.failed.map((p) => `${p.name} (${p.conclusion ?? 'red'})`).join('; ') : 'the run failed';
    return { action: 'red', why: red };
  }
  if (state === 'incomplete') return { action: 'red', why: `the run passed without ${parts.missing.map((p) => p.name).join(', ')}: no full matrix` };
  return { action: 'wait', why: parts ? partsLine(parts) : 'running' };
}

/** Whether the manifest `doc` offers `tag` with auto_ok on. */
export function autoOkIn(doc, tag) {
  const entry = (doc?.releases ?? []).find((r) => r?.version === tag);
  return entry ? entry.auto_ok === true : null;
}

function parseArgs(argv) {
  const o = { version: null, env: '', once: false, dry: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--env') o.env = argv[++i] ?? '';
    else if (a === '--once') o.once = true;
    else if (a === '--dry-run') o.dry = true;
    else if (a === '-h' || a === '--help') o.help = true;
    else if (a.startsWith('-')) throw new Error(`unknown option ${a}`);
    else if (!o.version) o.version = a.replace(/^v/, '');
    else throw new Error(`one version, not "${a}" too`);
  }
  if (!o.help && !/^\d+\.\d+\.\d+$/.test(o.version ?? '')) throw new Error('the release, as X.Y.Z');
  return o;
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function readManifest() {
  try {
    const res = await fetch(`${MANIFEST_URL}?t=${Date.now()}`, { headers: { 'cache-control': 'no-cache' }, signal: AbortSignal.timeout(20_000) });
    if (!res.ok) return { error: `${MANIFEST_URL} answered HTTP ${res.status}` };
    return { doc: await res.json() };
  } catch (e) {
    return { error: `${MANIFEST_URL}: ${e?.message ?? e}` };
  }
}

async function main(argv) {
  let o;
  try {
    o = parseArgs(argv);
  } catch (e) {
    console.error(`matrix-watch: ${e.message}\n\n${usageOf(import.meta.url)}`);
    return 2;
  }
  if (o.help) {
    console.log(usageOf(import.meta.url));
    return 0;
  }
  const version = o.version;
  const tag = `v${version}`;
  const gitDir = gitOut(REPO, 'rev-parse', '--absolute-git-dir');
  const stFile = stateFile(gitDir, tag);
  const record = loadState(stFile);
  const say = (m) => console.log(`matrix-watch ${tag}: ${m}`);
  if (!record) {
    console.error(`matrix-watch: no record of ${tag} here (${stFile}): run it where the release was cut`);
    return 2;
  }
  if (record.profile !== 'server') {
    console.error(`matrix-watch: ${tag} is a ${record.profile ?? 'minor'} release - its matrix was read before its tag; only a server patch goes out ahead of it`);
    return 2;
  }
  const sha = record.exportHead;
  if (!sha) {
    console.error(`matrix-watch: ${tag}'s record has no export commit (the land stage writes it)`);
    return 2;
  }
  const settings = loadSettings({ file: o.env, envVar: 'FILEX_TRAIN_ENV', fallback: 'filex-train.env' });
  const planModule = await import(pathToFileURL(path.join(HERE, 'plan.mjs')).href);
  const plan = planModule.default({ repo: REPO, version, tag });
  const gh = plan.github;
  const expected = plan.githubMatrix.parts({ repo: REPO });
  const wait = { pollMs: 60_000, timeoutMs: 3 * 3600_000, appearMs: 15 * 60_000, ...(plan.matrixWatch ?? {}) };
  const t0 = Date.now();
  let unanswered = 0;
  let shown = '';
  let v;
  for (;;) {
    const ci = gh.runs({ workflow: 'ci.yml', sha, event: 'push' });
    let error = ci.error ?? '';
    let parts = null;
    const run = error ? null : runVerdict(ci.runs);
    if (!error && run.run) {
      const jr = gh.jobs({ runId: run.run.id });
      if (jr.error) error = jr.error;
      else parts = partsVerdict(jr.jobs, expected, { finished: run.state !== 'running' });
    }
    if (error) {
      if (transientGithubError(error) && unanswered < 10) {
        unanswered += 1;
        await sleep(wait.pollMs);
        continue;
      }
      say(`could not ask GitHub: ${error}`);
      return 2;
    }
    unanswered = 0;
    v = watchVerdict(run.state, parts);
    const line = `${run.run?.url ?? 'ci.yml'}: ${v.action} - ${v.why}`;
    if (line !== shown) {
      say(line);
      shown = line;
    }
    if (v.action !== 'wait') break;
    if (o.once || Date.now() - t0 >= wait.timeoutMs || (run.state === 'none' && Date.now() - t0 >= wait.appearMs)) {
      say(`not finished${o.once ? '' : ` after ${Math.round((Date.now() - t0) / 60_000)} min`}; run me again later`);
      return 3;
    }
    await sleep(wait.pollMs);
  }

  const record2 = loadState(stFile) ?? record;
  const note = (fields) => {
    if (o.dry) return;
    const lock = takeLock(`${stFile}.lock`);
    if (lock.held) {
      say(`the release of ${tag} is running (pid ${lock.held}); its record is not written now`);
      return;
    }
    try {
      const st = loadState(stFile) ?? record2;
      st.matrix = { ...fields, sha, at: new Date().toISOString() };
      saveState(stFile, st);
    } finally {
      lock.release?.();
    }
  };

  if (v.action === 'red') {
    note({ state: 'red', why: v.why });
    say(`RED: ${v.why}. auto_ok stays off for ${tag}: no install takes it by itself.`);
    if (!o.dry) {
      await announce(settings.env, {
        title: `filex ${tag}: GitHub's full matrix is RED behind the server patch - auto_ok stays off`,
        message: [`${shown}`, '', `Installs that update by themselves do not take ${tag}; asked, they still can.`, `When it is fixed: a new patch, or after a re-run that passed, node scripts/release/matrix-watch.mjs ${version}`].join('\n'),
        result: 'red',
      }, { log: (l) => say(`notify: ${l}`) });
    }
    return 1;
  }

  // Green: auto_ok on, read back.
  const before = await readManifest();
  if (!before.error && autoOkIn(before.doc, tag) === true) {
    note({ state: 'green', auto_ok: true, why: v.why });
    say(`green, and ${MANIFEST_URL} already offers ${tag} with auto_ok on`);
    return 0;
  }
  const { cfg } = shipSettings(settings.env);
  if (!cfg.manifestCmd) {
    say('green, and SHIP_MANIFEST_CMD is not set: switch auto_ok on by hand (FILEX_MANIFEST_AUTO=<tag> with the manifest publishing command)');
    return 1;
  }
  if (o.dry) {
    say(`green: would run ${cfg.manifestCmd} with FILEX_MANIFEST_AUTO=${tag}`);
    return 0;
  }
  const bash = findBash() ?? 'bash';
  const pub = spawnSync(bash, ['-c', cfg.manifestCmd], { cwd: REPO, encoding: 'utf8', env: { ...process.env, ...settings.env, FILEX_MANIFEST_AUTO: tag }, windowsHide: true, maxBuffer: 16 * 1024 * 1024 });
  process.stdout.write(pub.stdout ?? '');
  process.stderr.write(pub.stderr ?? '');
  if (pub.status !== 0) {
    say(`the manifest command exited ${pub.status}`);
    return 1;
  }
  if (cfg.host && cfg.purgeCmd) {
    const purge = spawnSync(bash, ['-c', `${sshWords(cfg)} ${shq(`${cfg.purgeCmd} ${MANIFEST_URL}`)}`], { encoding: 'utf8', windowsHide: true });
    say(purge.status === 0 ? `purged ${MANIFEST_URL} from the CDN` : `the purge exited ${purge.status}: ${(purge.stderr || purge.stdout).trim().split('\n').at(-1)}`);
  }
  const after = await readManifest();
  const on = after.error ? null : autoOkIn(after.doc, tag);
  note({ state: 'green', auto_ok: on === true, why: v.why });
  const ok = on === true;
  say(ok ? `${MANIFEST_URL} offers ${tag} with auto_ok on` : `${MANIFEST_URL} does not show auto_ok on for ${tag} (${after.error ?? `auto_ok ${on}`})`);
  await announce(settings.env, {
    title: `filex ${tag}: GitHub's full matrix is green${ok ? ' - auto_ok is on' : ', but auto_ok did not turn on'}`,
    message: [shown, ok ? `Installs that update by themselves take ${tag} now.` : `Read ${MANIFEST_URL}; switch it with FILEX_MANIFEST_AUTO=${tag} and the manifest command.`].join('\n'),
    result: ok ? 'ok' : 'red',
  }, { log: (l) => say(`notify: ${l}`) });
  return ok ? 0 : 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then(
    (code) => process.exit(code),
    (e) => {
      console.error(`matrix-watch: ${e?.stack ?? e}`);
      process.exit(2);
    },
  );
}

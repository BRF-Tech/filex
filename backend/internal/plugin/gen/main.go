// Command gen writes driver_shapes.go: one concrete type per capability
// combination a plugin can declare.
//
// # Why a generator
//
// filex decides what a storage can do by TYPE-ASSERTING optional interfaces
// (storage.Writer, storage.Toucher, storage.Presigner …) at forty-odd call
// sites. A plugin that cannot write must therefore be handed to filex as a
// value that has NO Write method — not one that returns an error, or the UI
// offers an upload button, a trash move and a version snapshot that each fail
// at the last moment.
//
// With one optional axis that is two types. With five — write, mtime, watch,
// presign, multipart — it is twenty, and twenty hand-written structs is a
// place where somebody eventually embeds the wrong thing and a read-only
// plugin quietly becomes writable. So they are generated, and
// driver_shapes_test.go asserts the generated file is what this program
// produces.
//
//	go run ./internal/plugin/gen > internal/plugin/driver_shapes.go
package main

import (
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

// axis is one optional capability: the suffix it adds to a type name, the
// ops struct that implements it, and the storage interface it satisfies.
type axis struct {
	letter string // suffix in the type name
	field  string // embedded ops field
	iface  string // storage interface it provides (for the assertion table)
	// needsWrite marks axes that only make sense on a writable driver.
	needsWrite bool
}

var axes = []axis{
	{letter: "T", field: "touchOps", iface: "storage.Toucher", needsWrite: true},
	{letter: "W", field: "watchOps", iface: "storage.Watcher"},
	{letter: "P", field: "presignOps", iface: "storage.Presigner"},
	{letter: "M", field: "multipartOps", iface: "storage.PartUploader", needsWrite: true},
}

func main() {
	var b strings.Builder
	b.WriteString(`// Code generated by "go run ./internal/plugin/gen"; DO NOT EDIT.
//
// One concrete type per capability combination a plugin can declare. See
// gen/main.go for why these are generated rather than written by hand, and
// driver.go for what each ops struct does.

package plugin

import "github.com/brf-tech/filex/backend/internal/storage"

`)

	type shape struct {
		name   string
		fields []string
		write  bool
		mask   int
	}
	var shapes []shape

	for _, write := range []bool{false, true} {
		for mask := 0; mask < 1<<len(axes); mask++ {
			name := "drvR"
			fields := []string{"readOps"}
			if write {
				name = "drvX"
				fields = append(fields, "writeOps")
			}
			skip := false
			for i, a := range axes {
				if mask&(1<<i) == 0 {
					continue
				}
				if a.needsWrite && !write {
					skip = true // e.g. set_mtime on a read-only driver
					break
				}
				name += a.letter
				fields = append(fields, a.field)
			}
			if skip {
				continue
			}
			shapes = append(shapes, shape{name: name, fields: fields, write: write, mask: mask})
		}
	}
	sort.Slice(shapes, func(i, j int) bool {
		if shapes[i].write != shapes[j].write {
			return !shapes[i].write
		}
		return shapes[i].mask < shapes[j].mask
	})

	b.WriteString("type (\n")
	for _, s := range shapes {
		b.WriteString("\t" + s.name + " struct {\n")
		for _, f := range s.fields {
			b.WriteString("\t\t*" + f + "\n")
		}
		b.WriteString("\t}\n")
	}
	b.WriteString(")\n\n")

	// Compile-time proof that each shape satisfies exactly what its name says.
	// (Go cannot state the negative — that a read-only shape does NOT satisfy
	// storage.Writer — so driver_test.go asserts that at run time.)
	b.WriteString("var (\n")
	for _, s := range shapes {
		b.WriteString(fmt.Sprintf("\t_ storage.Driver      = %s{}\n", s.name))
		b.WriteString(fmt.Sprintf("\t_ storage.RangeReader = %s{}\n", s.name))
		if s.write {
			b.WriteString(fmt.Sprintf("\t_ storage.Writer      = %s{}\n", s.name))
			b.WriteString(fmt.Sprintf("\t_ storage.Deleter     = %s{}\n", s.name))
			b.WriteString(fmt.Sprintf("\t_ storage.Mover       = %s{}\n", s.name))
			b.WriteString(fmt.Sprintf("\t_ storage.Copier      = %s{}\n", s.name))
			b.WriteString(fmt.Sprintf("\t_ storage.Mkdirer     = %s{}\n", s.name))
		}
		for i, a := range axes {
			if s.mask&(1<<i) != 0 && (!a.needsWrite || s.write) {
				b.WriteString(fmt.Sprintf("\t_ %-21s = %s{}\n", a.iface, s.name))
			}
		}
	}
	b.WriteString(")\n\n")

	// newShape picks the type for a capability set.
	b.WriteString(`// newShape returns the concrete driver type whose method set matches caps
// exactly. The switch is exhaustive over the same combinations the type list
// above declares, so a capability set can never fall through to a shape that
// offers more than the plugin promised.
func newShape(r *readOps, x *writeOps, t *touchOps, w *watchOps, p *presignOps, m *multipartOps, caps Capabilities) storage.Driver {
	write := caps.Writable()
	switch {
`)
	for i := len(shapes) - 1; i >= 0; i-- {
		s := shapes[i]
		var conds []string
		if s.write {
			conds = append(conds, "write")
		} else {
			conds = append(conds, "!write")
		}
		for j, a := range axes {
			flag := map[string]string{"T": "caps.SetMtime", "W": "caps.Watch", "P": "caps.Presign", "M": "caps.Multipart"}[a.letter]
			if s.mask&(1<<j) != 0 && (!a.needsWrite || s.write) {
				conds = append(conds, flag)
			} else {
				conds = append(conds, "!"+flag)
			}
		}
		var args []string
		for _, f := range s.fields {
			switch f {
			case "readOps":
				args = append(args, "r")
			case "writeOps":
				args = append(args, "x")
			case "touchOps":
				args = append(args, "t")
			case "watchOps":
				args = append(args, "w")
			case "presignOps":
				args = append(args, "p")
			case "multipartOps":
				args = append(args, "m")
			}
		}
		b.WriteString(fmt.Sprintf("\tcase %s:\n\t\treturn %s{%s}\n", strings.Join(conds, " && "), s.name, strings.Join(args, ", ")))
	}
	b.WriteString("\t}\n\t// Unreachable: the cases above cover every combination.\n\treturn drvR{r}\n}\n")

	// Formatted here, not left to whoever remembers to run gofmt afterwards:
	// the committed file is gofmt'd, so a generator that emits unaligned
	// source makes "regenerate and diff" report a difference that is not a
	// difference — and that noise is how a real drift gets waved through.
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "generated source does not parse:", err)
		os.Exit(1)
	}
	if _, err := os.Stdout.Write(out); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// winget manifests and the Homebrew cask for ONE desktop release.
//
//   node scripts/pkg-manifests.mjs --version 0.43.3 \
//        --windows release/filex-desktop-x64.exe --mac release/filex-desktop-arm64.dmg \
//        --out ../pkg-out
//
// writes
//   <out>/winget/manifests/b/BRFTech/filex-app/<version>/BRFTech.filex-app{,.installer,.locale.en-US,.locale.tr-TR}.yaml
//   <out>/homebrew/Casks/filex-app.rb
//
// The paths are the ones winget-pkgs and a Homebrew tap expect, so the release
// job hands the first to `wingetcreate submit` and commits the second to the
// tap as they are. Either input may be left out; that store is then skipped.
//
// ⚠⚠ The URL written into both is the VERSIONED one
// (…/releases/download/v<version>/<file>), never `latest/download`: winget and
// Homebrew pin the file by its SHA-256, and a link whose target changes every
// release would fail that check for everybody the day the next one ships. The
// flip side: once a tag's manifests are submitted, that tag's assets must never
// be re-uploaded (`gh release upload --clobber`) — new bytes under the same URL
// break every install of that version. A fix ships as a new patch release.
//
// Names (Burak, 2026-09-25): the desktop app is `filex-app` in every package
// manager, the CLI is plain `filex` — the command's own name, which is what a
// developer types after `brew install` or `winget install` (Homebrew's own
// rule for an app beside a same-named tool: tailscale/tailscale-app,
// ollama/ollama-app). The CLI is not here: goreleaser publishes it from the
// same release.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// ── identities — permanent once submitted; change them only before the first ──
export const WINGET_ID = 'BRFTech.filex-app';
export const CASK_TOKEN = 'filex-app';
const PUBLISHER = 'BRF Tech'; // what the NSIS installer writes as Publisher in Apps & features
const REPO = 'https://github.com/BRF-Tech/filex';
// electron-builder derives the NSIS uninstall key from appId (UUID v5), so it
// is the same for every version; winget matches the installed app by it.
// Measured on an installed copy: HKCU\…\Uninstall\af48dd76-2015-5c31-806d-7410b4687915.
const PRODUCT_CODE = 'af48dd76-2015-5c31-806d-7410b4687915';
// The Office types "Open with filex" registers (src/openwith.ts OFFICE_EXTENSIONS;
// test/pkg-manifests.test.ts keeps the two equal).
export const FILE_EXTENSIONS = ['docx', 'doc', 'xlsx', 'xls', 'pptx', 'ppt', 'odt', 'ods', 'odp', 'rtf'];
/**
 * The oldest macOS the bundled Electron runs on, as a Homebrew symbol — read
 * from the Electron in package.json at render time, so an upgrade cannot leave
 * the cask promising a macOS the app no longer starts on. Electron's own
 * floors: 38 → macOS 12, 44 → macOS 13 (LSMinimumSystemVersion 13.0). The
 * build is arm64-only and Apple Silicon started at macOS 11, so nothing goes
 * below Big Sur.
 */
export function macosMinFor(electronMajor) {
  if (electronMajor >= 44) return ':ventura';
  if (electronMajor >= 38) return ':monterey';
  return ':big_sur';
}

function electronMajor() {
  const pkg = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
  const m = /(\d+)\./.exec(pkg.devDependencies?.electron ?? '');
  if (!m) throw new Error('desktop/package.json has no electron devDependency');
  return Number(m[1]);
}

const SCHEMA = '1.12.0';

export function assetUrl(version, file) {
  return `${REPO}/releases/download/v${version}/${file}`;
}

export function sha256(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

const header = (kind) =>
  `# Generated by desktop/scripts/pkg-manifests.mjs — edit the generator, not this file.\n` +
  `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${kind}.${SCHEMA}.schema.json\n\n`;

/** Quotes a YAML scalar only when it has to. */
function y(s) {
  return /^[\w.\/:@+-][\w .\/:@+,()-]*$/.test(s) && !/^(yes|no|true|false|null|on|off)$/i.test(s) ? s : JSON.stringify(s);
}

export function wingetManifests({ version, sha, releaseDate }) {
  const version_ = header('version') + [
    `PackageIdentifier: ${WINGET_ID}`,
    `PackageVersion: ${version}`,
    'DefaultLocale: en-US',
    'ManifestType: version',
    `ManifestVersion: ${SCHEMA}`,
    '',
  ].join('\n');

  const installer = header('installer') + [
    `PackageIdentifier: ${WINGET_ID}`,
    `PackageVersion: ${version}`,
    // electron-builder's NSIS installer; per-user only (electron-builder.yml:
    // perMachine false + allowElevation false), silent with /S.
    'InstallerType: nullsoft',
    'Scope: user',
    'InstallModes:',
    '- interactive',
    '- silent',
    '- silentWithProgress',
    'InstallerSwitches:',
    '  Custom: /currentuser',
    // The flag electron-updater's own swap passes: the app comes back in the
    // tray instead of throwing a window at whoever ran `winget upgrade`.
    '  Upgrade: --updated',
    'UpgradeBehavior: install',
    'Protocols:',
    '- filex',
    'FileExtensions:',
    ...FILE_EXTENSIONS.map((e) => `- ${e}`),
    `ProductCode: ${PRODUCT_CODE}`,
    ...(releaseDate ? [`ReleaseDate: ${releaseDate}`] : []),
    'AppsAndFeaturesEntries:',
    `- DisplayName: filex ${version}`,
    `  Publisher: ${PUBLISHER}`,
    `  DisplayVersion: ${version}`,
    `  ProductCode: ${PRODUCT_CODE}`,
    'Installers:',
    '- Architecture: x64',
    `  InstallerUrl: ${assetUrl(version, 'filex-desktop-x64.exe')}`,
    `  InstallerSha256: ${sha.toUpperCase()}`,
    'ManifestType: installer',
    `ManifestVersion: ${SCHEMA}`,
    '',
  ].join('\n');

  const common = [
    `PackageIdentifier: ${WINGET_ID}`,
    `PackageVersion: ${version}`,
  ];
  const tail = (type) => [`ManifestType: ${type}`, `ManifestVersion: ${SCHEMA}`, ''];

  const en = header('defaultLocale') + [
    ...common,
    'PackageLocale: en-US',
    `Publisher: ${PUBLISHER}`,
    `PublisherUrl: ${REPO}`,
    `PublisherSupportUrl: ${REPO}/issues`,
    'PrivacyUrl: https://filex.sh/privacy/',
    'PackageName: filex',
    'PackageUrl: https://filex.sh/',
    'License: MIT',
    `LicenseUrl: ${REPO}/blob/main/LICENSE`,
    'Copyright: © BRF Tech',
    `ShortDescription: ${y('Desktop app for filex, the self-hosted file manager — browse your server, sync folders, open Office documents.')}`,
    `Description: ${y('filex connects to a filex server that you or your organisation run. Sign in through your browser, browse and share the server\'s files in a native window, keep folders on this computer in two-way sync in the background, and drag files out onto the desktop.')}`,
    'Moniker: filex-app',
    'Tags:',
    ...['file-manager', 'file-sync', 'self-hosted', 'webdav', 'sftp', 's3', 'cloud-storage'].map((t) => `- ${t}`),
    `ReleaseNotesUrl: ${REPO}/releases/tag/v${version}`,
    ...tail('defaultLocale'),
  ].join('\n');

  const tr = header('locale') + [
    ...common,
    'PackageLocale: tr-TR',
    `Publisher: ${PUBLISHER}`,
    'PackageName: filex',
    'License: MIT',
    `ShortDescription: ${y('Kendi sunucunuzda çalışan dosya yöneticisi filex\'in masaüstü uygulaması — sunucunuzda gezinin, klasörleri senkronlayın, Office belgelerini açın.')}`,
    `Description: ${y('filex, sizin ya da kurumunuzun işlettiği bir filex sunucusuna bağlanır. Tarayıcınızla giriş yapın, sunucudaki dosyalarda yerel bir pencerede gezinip paylaşın, bu bilgisayardaki klasörleri arka planda iki yönlü senkronda tutun, dosyaları masaüstüne sürükleyin.')}`,
    ...tail('locale'),
  ].join('\n');

  const base = `${WINGET_ID}`;
  return {
    [`${base}.yaml`]: version_,
    [`${base}.installer.yaml`]: installer,
    [`${base}.locale.en-US.yaml`]: en,
    [`${base}.locale.tr-TR.yaml`]: tr,
  };
}

/** winget-pkgs' directory for a package: manifests/<first letter>/<Publisher>/<Name…>/<version>. */
export function wingetDir(version) {
  const parts = WINGET_ID.split('.');
  return path.join('manifests', parts[0][0].toLowerCase(), ...parts, version);
}

export function homebrewCask({ version, sha, macosMin = macosMinFor(electronMajor()) }) {
  return `# Generated by desktop/scripts/pkg-manifests.mjs in github.com/BRF-Tech/filex —
# edit the generator, not this file; the release job overwrites it.
cask "${CASK_TOKEN}" do
  version "${version}"
  sha256 "${sha}"

  url "${REPO}/releases/download/v#{version}/filex-desktop-arm64.dmg"
  name "filex"
  desc "Desktop app for the self-hosted filex file manager"
  homepage "https://filex.sh/"

  livecheck do
    url :url
    strategy :github_latest
  end

  # The macOS build cannot replace itself (it is ad-hoc sealed, not signed with
  # a Developer ID), so \`brew upgrade\` is what updates it.
  auto_updates false
  depends_on arch: :arm64
  depends_on macos: ">= ${macosMin}"

  app "filex.app"

  # Only the desktop app's own files. ~/.filex is shared with the filex CLI
  # (sync pairs, baselines) and is left alone.
  zap trash: [
    "~/.filex/desktop",
    "~/Library/Application Support/@brftech/filex-desktop",
    "~/Library/Preferences/sh.brf.filex.desktop.plist",
    "~/Library/Saved Application State/sh.brf.filex.desktop.savedState",
  ]

  # No Developer ID (Burak, 2026-09-25): the app is ad-hoc sealed, and Homebrew
  # keeps macOS's quarantine on what a cask downloads, so the first launch is
  # stopped once and the user lets it through. Said here rather than worked
  # around: removing the quarantine for them is exactly what Homebrew declines
  # to make easy.
  caveats <<~EOS
    filex is not signed with an Apple Developer ID, so macOS blocks its first
    launch. Open it once, then go to System Settings → Privacy & Security and
    click "Open Anyway" next to filex.
  EOS
end
`;
}

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    if (!k.startsWith('--')) throw new Error(`unexpected argument ${k}`);
    out[k.slice(2)] = argv[++i];
  }
  return out;
}

export function run(argv) {
  const a = parseArgs(argv);
  if (!a.version || !/^\d+\.\d+\.\d+$/.test(a.version)) throw new Error('--version x.y.z is required');
  if (!a.out) throw new Error('--out <dir> is required');
  if (!a.windows && !a.mac) throw new Error('give --windows and/or --mac');
  const written = [];
  if (a.windows) {
    const dir = path.join(a.out, 'winget', wingetDir(a.version));
    fs.mkdirSync(dir, { recursive: true });
    const files = wingetManifests({ version: a.version, sha: sha256(a.windows), releaseDate: a['release-date'] });
    for (const [name, body] of Object.entries(files)) {
      fs.writeFileSync(path.join(dir, name), body);
      written.push(path.join(dir, name));
    }
  }
  if (a.mac) {
    const dir = path.join(a.out, 'homebrew', 'Casks');
    fs.mkdirSync(dir, { recursive: true });
    const file = path.join(dir, `${CASK_TOKEN}.rb`);
    fs.writeFileSync(file, homebrewCask({ version: a.version, sha: sha256(a.mac) }));
    written.push(file);
  }
  return written;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    for (const f of run(process.argv.slice(2))) console.log(`wrote ${f}`);
  } catch (e) {
    console.error(String(e?.message ?? e));
    process.exit(1);
  }
}
